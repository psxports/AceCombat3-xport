static const uint8 *ui_item_dispatch_command(uint32 opcode, UI_COMMAND_STREAM command, uint32 ordering, const UI_ITEM *context)
{
    switch (opcode)
    {
        case 0:
            return ui_command_draw_tile(command, ordering, context);
        case 1:
            return ui_command_draw_sprite(command, ordering, context);
        case 2:
            return ui_command_set_draw_mode(command, ordering);
        case 3:
            return ui_command_draw_textured_quad(command, ordering, context);
        case 4:
            return ui_command_skip(command);
        case 5:
            return ui_control_select(command);
        case 6:
            return ui_command_draw_line(command, ordering, context);
        default:
#ifndef NDEBUG
            fprintf(stderr, "Unbound resource2 command opcode %u\n", opcode);
#endif
            abort();
    }
}

static void ui_item_dispatch_final_hook(uint32 group, uint32 index)
{
    switch (group * UI_ITEM_COUNT + index)
    {
        case 1:
            menu_orbits_render();
            return;
        case 12:
            ui_item_final_hook_0_12();
            return;
        case 15:
            ui_item_final_hook_0_15();
            return;
        case UI_ITEM_COUNT + 0:
            ui_item_final_hook_1_0();
            return;
        case UI_ITEM_COUNT + 4:
            ui_item_final_hook_1_4();
            return;
        default:
            ui_item_final_hook_default();
            return;
    }
}

void ui_item_render(uint32 index, uint32 group)
{
    uint32 wire_word_0;
    uint16 wire_halfword_1;
#if 0
    uint32 ordering, command;
#else
    uint32 ordering, command;
    uint32 settings_panel = 0;
    sint32 saved_y;
#endif

    UI_ITEM *context;
    UI_COMMAND_STREAM commands;
    const uint8 *stream, *end;
    static const uint8 command_bytes[] = {24, 32, 16, 36, 20, 20, 24};

    FUNCTION_MARKER(0x800E22E4, "ACE3.BIN");
    if (group >= UI_ITEM_GROUP_COUNT || index >= UI_ITEM_COUNT)
        abort();
    ordering = ui_packets.scene_ot;
    commands = ui_group_command_stream(group, index);
    stream = commands.data;
    end = stream + commands.bytes;
    if (group == 0)
        ui_item_step_motion(index);
    for (;;)
    {
        if (end - stream < 4)
            abort();
        command = (memcpy(&wire_word_0, stream, sizeof(wire_word_0)), wire_word_0);
        if (command == 0xFFFFFFFF)
            break;
        if (command >= sizeof(command_bytes) || end - stream < command_bytes[command])
            abort();
        context = ui_item_at(group, index);
#if 0
        stream = ui_item_dispatch_command(command, ui_command_directory(stream, command_bytes[command], 4, command_bytes[command]), ordering, context);
#else
        /* Settings panel order is audio, brightness, screen, game, footer */
        if (group == 2 && index == 12)
        {
            if (command == 5)
                ++settings_panel;
            if (settings_panel == 2 || settings_panel == 3 || (settings_panel == 5 && command == 0 && (sint16)(memcpy(&wire_halfword_1, stream + 6, sizeof(wire_halfword_1)), wire_halfword_1) >= 261))
            {
                stream += command_bytes[command];
                continue;
            }
        }
        saved_y = (sint16)context->y;
        if (group == 2 && index == 12 && settings_panel == 4)
            context->y = (uint16)((uint32)(saved_y - 136));
        stream = ui_item_dispatch_command(command, ui_command_directory(stream, command_bytes[command], 4, command_bytes[command]), ordering, context);
        if (group == 2 && index == 12 && settings_panel == 4)
            context->y = (uint16)((uint32)saved_y);
#endif
    }
    ui_item_dispatch_final_hook(group, index);
}

