void dialogue_sequence_reset(void)
{
    free(sequence.entries);
    memset(&sequence, 0, sizeof(sequence));
}

void dialogue_sequence_bind(DIALOGUE_SEQUENCE_SOURCE source, uint32 skip)
{
    uint32 count, index;
    uint16 *entries = NULL;
    const uint8 *row = source.data;
    uint32 bytes = source.bytes;

    if (!row || bytes < sizeof(uint32))
        abort();
    memcpy(&count, row, sizeof(count));
    if (skip > count)
        abort();
    if (count > (bytes - sizeof(uint32)) / sizeof(uint32))
        abort();
    if (count)
    {
        entries = malloc((size_t)count * sizeof(*entries));
        if (!entries)
            abort();
        for (index = 0; index < count; ++index)
            memcpy(entries + index, row + 4 + (size_t)index * 4, sizeof(*entries));
    }
    free(sequence.entries);
    sequence.entries = entries;
    sequence.count = count;
    sequence.cursor = skip;
    sequence.single = 0;
}

void dialogue_sequence_bind_single(void)
{
    free(sequence.entries);
    sequence.entries = NULL;
    sequence.count = 1;
    sequence.cursor = 0;
    sequence.single = 1;
}

uint32 dialogue_sequence_remaining(void)
{
    return sequence.count - sequence.cursor;
}

sint32 dialogue_sequence_id(sint32 relative)
{
    sint64 idx = (sint64)sequence.cursor + relative;

    if (idx < 0 || idx >= sequence.count)
        abort();
    if (sequence.single)
        return (sint16)sequence.sel_id;
    return (sint16)sequence.entries[(uint32)idx];
}

void dialogue_sequence_advance(void)
{
    if (sequence.cursor >= sequence.count)
        abort();
    ++sequence.cursor;
}

void dialogue_sequence_set_sel(uint32 id)
{
    sequence.sel_id = (uint16)id;
}

sint32 dialogue_sequence_sel_id(void)
{
    return (sint16)sequence.sel_id;
}

uint32 dialogue_sequence_unlock_archive(uint32 resource)
{
    uint32 group, index, value;

    FUNCTION_MARKER(0x800FEE68, "ACE3.BIN");
    for (group = 0; group < 62; ++group)
    {
        for (index = 0; index < 8; ++index)
        {
            value = archive_entries[group][index];
            if (value == resource)
            {
                if (game_runtime.progress.archive_status[group] == 0)
                    game_runtime.progress.archive_status[group] = 1;
            }
        }
    }
    return 0;
}

uint8 dialogue_sequence_movie_index(uint32 id)
{
    static const uint8 movie_index[] = {
        2, 4, 6, 7, 8, 9, 10, 11, 12,
        16, 18, 19, 21, 23, 25, 27, 28, 30,
    };
    enum { first_movie_id = 8 };

    if (id < first_movie_id || id - first_movie_id >= sizeof(movie_index))
        abort();
    return movie_index[id - first_movie_id];
}

const DIALOGUE_CATALOG_ENTRY *dialogue_sequence_entry(uint32 id)
{
    if (id >= sizeof(catalog) / sizeof(*catalog))
        abort();
    return catalog + id;
}
