static struct
{
    uint8 value[UI_WIDGET_COUNT];
} ui_widgets;

void ui_widgets_reset(void)
{
    memset(&ui_widgets, 0, sizeof(ui_widgets));
}

uint8 *ui_widget_value(uint32 index)
{
    if (index >= UI_WIDGET_COUNT)
        abort();
    return ui_widgets.value + index;
}

uint32 ui_widget_get(uint32 index)
{
    FUNCTION_MARKER(0x800DEE60, "ACE3.BIN");
    return *ui_widget_value(index);
}

void ui_widget_set(uint32 index, uint32 value)
{
    FUNCTION_MARKER(0x800DEF94, "ACE3.BIN");
    *ui_widget_value(index) = (uint8)value;
}
